# Layer 2 — grants (access control)
# ---------------------------------------------------------------------------

def grant_access(
    db: Session,
    project: Project,
    var: EnvironmentVariable,
    user_id: uuid.UUID,
    granted_by: uuid.UUID | None,
) -> dict:
    """Allow ONE member/agent of THIS project to retrieve ONE variable. No
    blanket project-member access is ever implied (Phase 5 Feature 3)."""
    target = db.get(User, user_id)
    if not target or target.project_id != project.id:
        from fastapi import HTTPException

        raise HTTPException(status_code=400, detail="user_id is not a member of this project")

    existing = db.scalar(
        select(EnvironmentAccess).where(
            EnvironmentAccess.environment_variable_id == var.id,
            EnvironmentAccess.user_id == user_id,
        )
    )
    if existing:
        return grant_out(existing, var, target)

    row = EnvironmentAccess(
        environment_variable_id=var.id, user_id=user_id, granted_by=granted_by
    )
    db.add(row)
    db.flush()
    _event(
        db,
        project.id,
        EVENT_ACCESS_GRANTED,
        {"key": var.key, "user_id": str(user_id), "granted_by": str(granted_by) if granted_by else None},
    )
    db.commit()
    return grant_out(row, var, target)


def revoke_access(
    db: Session,
    project: Project,
    grant: EnvironmentAccess,
    var: EnvironmentVariable,
    requesting_user_id: uuid.UUID | None,
) -> dict:
    require_owner_if_set(project, requesting_user_id)
    db.delete(grant)
    _event(
        db,
        project.id,
        EVENT_ACCESS_REVOKED,
        {"key": var.key, "user_id": str(grant.user_id)},
    )
    db.commit()
    return {"revoked": True, "id": str(grant.id)}


def get_grant(db: Session, project_id: uuid.UUID, grant_id: uuid.UUID) -> tuple[EnvironmentAccess, EnvironmentVariable] | None:
    row = db.get(EnvironmentAccess, grant_id)
    if not row:
        return None
    var = db.get(EnvironmentVariable, row.environment_variable_id)
    if not var or var.project_id != project_id:
        return None
    return row, var


def grants_for_variable(db: Session, var: EnvironmentVariable) -> list[dict]:
    rows = db.scalars(
        select(EnvironmentAccess).where(EnvironmentAccess.environment_variable_id == var.id)
    ).all()
    users = {
        u.id: u
        for u in db.scalars(
            select(User).where(User.id.in_([r.user_id for r in rows] or [uuid.uuid4()]))
        ).all()
    }
    return [
        {
            "id": str(r.id),
            "environment_variable_id": str(r.environment_variable_id),
            "key": var.key,
            "user_id": str(r.user_id),
            "user_name": users.get(r.user_id).name if users.get(r.user_id) else None,
            "granted_by": str(r.granted_by) if r.granted_by else None,
            "created_at": r.created_at.isoformat(),
        }
        for r in rows
    ]


def grant_out(row: EnvironmentAccess, var: EnvironmentVariable, user: User) -> dict:
    return {
        "id": str(row.id),
        "environment_variable_id": str(row.environment_variable_id),
        "key": var.key,
        "user_id": str(row.user_id),
        "user_name": user.name,
        "granted_by": str(row.granted_by) if row.granted_by else None,
        "created_at": row.created_at.isoformat(),
    }


# ---------------------------------------------------------------------------
# Layer 3 — the request flow (Feature 4) and authorized retrieval (Feature 5/10)
# ---------------------------------------------------------------------------

def request_secret(
    db: Session,
    project: Project,
    var: EnvironmentVariable,
    user: User,
) -> dict:
    """Agent/developer request flow: membership is already checked by the
    caller (require_member); this checks the GRANT, audits the outcome, and —
    only when authorized — returns the decrypted value.

    The value NEVER lands in an event payload, a log line, or any list
    endpoint: the retrieval response is the one and only carrier.
    """
    has_grant = db.scalar(
        select(EnvironmentAccess.id).where(
            EnvironmentAccess.environment_variable_id == var.id,
            EnvironmentAccess.user_id == user.id,
        )
    ) is not None

    _event(
        db,
        project.id,
        EVENT_SECRET_REQUESTED,
        {"key": var.key, "user_id": str(user.id), "user_name": user.name, "kind": user.kind},
    )
    if not has_grant:
        _event(
            db,
            project.id,
            EVENT_SECRET_DENIED,
            {"key": var.key, "user_id": str(user.id), "reason": "no access grant"},
        )
        db.commit()
        from fastapi import HTTPException

        raise HTTPException(
            status_code=403,
            detail="no access grant for this variable — ask the project owner to grant access",
        )

    try:
        value = secret_store.get_value(db, var.id)
    except Exception as exc:  # broken keyring/extension must fail closed, loudly
        db.rollback()
        from fastapi import HTTPException

        raise HTTPException(
            status_code=503,
            detail="secret store unavailable: value could not be decrypted",
        ) from exc

    if value is None:
        db.commit()
        from fastapi import HTTPException

        raise HTTPException(status_code=404, detail="variable is defined but not configured")

    _event(
        db,
        project.id,
        EVENT_SECRET_RETRIEVED,
        {"key": var.key, "user_id": str(user.id)},
    )
    db.commit()
    return {"key": var.key, "value": value}


def pull_environment(db: Session, project: Project, user: User) -> dict:
    """`scaffold env pull` core: every variable this member is AUTHORIZED for.
    No grant -> the variable is omitted entirely (never an error, never a
    value) so the command's output is exactly the safe superset of the
    caller's entitlement."""
    rows = db.execute(
        select(EnvironmentVariable, EnvironmentAccess.id)
        .join(EnvironmentAccess, EnvironmentAccess.environment_variable_id == EnvironmentVariable.id)
        .where(
            EnvironmentVariable.project_id == project.id,
            EnvironmentAccess.user_id == user.id,
        )
        .order_by(EnvironmentVariable.key.asc())
    ).all()
    out = []
    for var, _grant_id in rows:
        try:
            value = secret_store.get_value(db, var.id)
        except Exception:
            db.rollback()
            value = None
        out.append(
            {
                "key": var.key,
                "value": value,
                "description": var.description,
                "is_secret": var.is_secret,
            }
        )
    granted = len(out)
    _event(
        db,
        project.id,
        EVENT_SECRET_RETRIEVED,
        {"key": "*", "user_id": str(user.id), "count": granted, "via": "env_pull"},
    )
    db.commit()
    from sqlalchemy import func

    total_count = db.scalar(
        select(func.count()).where(EnvironmentVariable.project_id == project.id)
    ) or 0
    return {
        "project_id": str(project.id),
        "project_name": project.name,
        "values": out,
        "granted_count": granted,
        "total_count": total_count,
    }


# ---------------------------------------------------------------------------
# Template generation (Feature 6) — deterministic, value-free
# ---------------------------------------------------------------------------

def build_template(db: Session, project_id: uuid.UUID) -> dict:
    """`.env.example` contents: names + EMPTY values + a comment header from
    the metadata descriptions. Secrets and non-secrets look identical here —
    by design; a template carries no information about secretness."""
    rows = db.scalars(
        select(EnvironmentVariable)
        .where(EnvironmentVariable.project_id == project_id)
        .order_by(EnvironmentVariable.key.asc())
    ).all()
    return {
        "project_id": str(project_id),
        "project_name": None,  # filled by the route (needs the project row)
        "filename": ".env.example",
        "variables": [{"key": r.key, "description": r.description} for r in rows],
        "content": template_lines(
            [{"key": r.key} for r in rows]
        ),
        "count": len(rows),
    }


