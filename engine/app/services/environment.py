AUDIT_EVENT_TYPES = (
    EVENT_VARIABLE_DEFINED,
    EVENT_VALUE_SET,
    EVENT_ACCESS_GRANTED,
    EVENT_ACCESS_REVOKED,
    EVENT_SECRET_REQUESTED,
    EVENT_SECRET_DENIED,
    EVENT_SECRET_RETRIEVED,
    EVENT_SECRET_ROTATED,
    EVENT_VARIABLE_REMOVED,
    "env_variable_updated",
)


def audit_log(db: Session, project_id: uuid.UUID, limit: int = 50) -> list[dict]:
    """Newest audit events first. Payloads are stored value-free (see the event
    writers above) — this is a plain read, nothing to scrub."""
    rows = db.scalars(
        select(Event)
        .where(
            Event.project_id == project_id,
            Event.type.in_(AUDIT_EVENT_TYPES),
        )
        .order_by(Event.created_at.desc())
        .limit(min(max(limit, 1), 200))
    ).all()
    return [
        {
            "id": str(e.id),
            "type": e.type,
            "payload": e.payload,
            "created_at": e.created_at.isoformat(),
        }
        for e in rows
    ]
