"""environment.py — Phase 5 (secure environment) deterministic service layer.

The three-layer model (kept strictly separate per the Phase 5 brief):

    Layer 1  METADATA    what variables exist          environment_variables
    Layer 2  PERMISSIONS who may retrieve what         environment_access
    Layer 3  VALUES      the actual secret bytes       scaffold_secrets (secret_store.py)

Everything in THIS module is deterministic plain SQL/Python (repo rule #3) over
layers 1-2; layer 3 is delegated entirely to services/secret_store.py, which is
the only module allowed to touch ciphertext.

Audit trail (Feature 8): access decisions are written to the existing `events`
table as new additive event types — `env_variable_defined`, `env_value_set`,
`env_access_granted`, `env_access_revoked`, `env_secret_requested`,
`env_secret_access_denied`, `env_secret_retrieved`, `env_secret_rotated`,
`env_variable_removed`. Payloads carry ids, names, and outcomes ONLY — the
Phase 5 hard rule "log that access happened, never the secret itself" is
enforced here: no code path can put a value into a payload because values
never pass through this module at all.
"""

from __future__ import annotations

import re
import uuid
from datetime import datetime

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.db.models import EnvironmentAccess, EnvironmentVariable, Event, Project, User
from app.services import secret_store

ENV_KEY_RE = re.compile(r"^[A-Z][A-Z0-9_]*$")
MAX_ENV_KEY_LEN = 120
MAX_ENV_DESCRIPTION_LEN = 500

EVENT_VARIABLE_DEFINED = "env_variable_defined"
EVENT_VALUE_SET = "env_value_set"
EVENT_ACCESS_GRANTED = "env_access_granted"
EVENT_ACCESS_REVOKED = "env_access_revoked"
EVENT_SECRET_REQUESTED = "env_secret_requested"
EVENT_SECRET_DENIED = "env_secret_access_denied"
EVENT_SECRET_RETRIEVED = "env_secret_retrieved"
EVENT_SECRET_ROTATED = "env_secret_rotated"
EVENT_VARIABLE_REMOVED = "env_variable_removed"


class EnvKeyInvalid(ValueError):
    """The variable name fails the shape rule (SCREAMING_SNAKE_CASE)."""


# ---------------------------------------------------------------------------
# Pure helpers (no DB, no clock reads — unit-testable without Postgres)
# ---------------------------------------------------------------------------

def validate_key(key: str) -> str:
    """SCREAMING_SNAKE_CASE only — an env var key is not free text (it lands in
    generated .env.example files and audit events)."""
    k = (key or "").strip()
    if not k or len(k) > MAX_ENV_KEY_LEN or not ENV_KEY_RE.fullmatch(k):
        raise EnvKeyInvalid(
            "key must be SCREAMING_SNAKE_CASE (letters, digits, underscores, "
            "starting with a letter)"
        )
    return k


def status_of(variable: dict, configured: bool) -> str:
    """Dashboard status word — exactly the four the Phase 5 brief lists.
    Pure function so the UI wording can never drift from the API."""
    if configured:
        return "configured"
    return "required_missing" if variable.get("required") else "optional_missing"


def display_status(status: str) -> str:
    """Human label for the status word (UI copy lives next to the logic)."""
    return {
        "configured": "Configured",
        "required_missing": "Required · Missing",
        "optional_missing": "Optional · Not configured",
    }[status]


def template_lines(rows: list[dict]) -> str:
    """`.env.example` body: names with EMPTY values, never a value, ever.
    The description is available separately (the `description` metadata field
    is served by GET /environment and the template endpoint's header)."""
    return "\n".join(f"{r['key']}=" for r in rows)


def pull_file_body(project_name: str, rows: list[dict]) -> str:
    """Body of the generated `.env.scaffold` file for `scaffold env pull`.
    Values come from the AUTHORIZED retrieval — the file is written by the
    developer's local command, never rendered in any UI. Non-secret values and
    secrets live here side by side: the file itself is the controlled artifact
    (gitignored pattern, review-before-use workflow)."""
    lines = [
        f"# .env.scaffold — generated by Scaffold env pull for project '{project_name}'.",
        "# Review before use. NEVER commit this file (.env* is gitignored; verify your",
        "# repo's .gitignore covers it). Scaffold's canonical template lives in .env.example.",
        "",
    ]
    for r in rows:
        desc = (r.get("description") or "").strip()
        if desc:
            lines.append(f"# {desc}")
        lines.append(f"{r['key']}={r.get('value') or ''}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


