def _event(db: Session, project_id: uuid.UUID, type_: str, payload: dict) -> None:
    db.add(Event(project_id=project_id, type=type_, payload=payload))


def get_project(db: Session, project_id: uuid.UUID) -> Project:
    project = db.get(Project, project_id)
    if not project:
        from fastapi import HTTPException

        raise HTTPException(status_code=404, detail="project not found")
    return project


def require_member(db: Session, project_id: uuid.UUID, user_id: uuid.UUID | None) -> User:
    """The requester must be an ACTIVE member of THIS project — the Phase 5
    membership check. Project isolation: a user id from another project (or a
    removed member) can never see this project's environment."""
    if user_id is None:
        from fastapi import HTTPException

        raise HTTPException(status_code=400, detail="user_id is required")
    user = db.get(User, user_id)
    if not user or user.project_id != project_id or user.membership_status == "removed":
        from fastapi import HTTPException

        raise HTTPException(
            status_code=403,
            detail="requester is not an active member of this project",
        )
    return user


def require_owner_if_set(project: Project, requesting_user_id: uuid.UUID | None) -> None:
    """Owner-gate for metadata/grant mutations — the exact placeholder trust
    model every other owner-gated route uses (see routes/team.py): compared
    server-side to projects.owner_user_id; open until an owner is claimed."""
    if project.owner_user_id is None:
        return
    if requesting_user_id is None or requesting_user_id != project.owner_user_id:
        from fastapi import HTTPException

        raise HTTPException(status_code=403, detail="only the project owner can perform this action")


def list_variables(db: Session, project_id: uuid.UUID) -> list[dict]:
    """Layer 1 + a computed configured flag (layer 3 touched ONLY as a boolean —
    never a value). Bounded output; safe for the dashboard."""
    rows = db.scalars(
        select(EnvironmentVariable)
        .where(EnvironmentVariable.project_id == project_id)
        .order_by(EnvironmentVariable.key.asc())
    ).all()
    return [
        {
            "id": str(v.id),
            "project_id": str(v.project_id),
            "key": v.key,
            "description": v.description,
            "required": v.required,
            "is_secret": v.is_secret,
            "created_by": str(v.created_by) if v.created_by else None,
            "created_at": v.created_at.isoformat(),
            "updated_at": v.updated_at.isoformat(),
            "configured": has_value(db, v.id),
        }
        for v in rows
    ]


def has_value(db: Session, environment_variable_id: uuid.UUID) -> bool:
    """Configured = a ciphertext row exists. This is the ONLY bit of layer 3
    that metadata consumers ever learn (a boolean, never bytes)."""
    from sqlalchemy import text

    row = db.execute(
        text(
            "SELECT 1 FROM scaffold_secrets.environment_secrets "
            "WHERE environment_variable_id = :id LIMIT 1"
        ),
        {"id": environment_variable_id},
    ).first()
    return row is not None


def define_variable(
    db: Session,
    project_id: uuid.UUID,
    key: str,
    description: str | None,
    required: bool,
    is_secret: bool,
    created_by: uuid.UUID | None,
    value: str | None = None,
) -> dict:
    """Create (or re-describe) a variable. With `value`, the initial value is
    stored through the secret store in the same transaction."""
    try:
        clean_key = validate_key(key)
    except EnvKeyInvalid as exc:
        from fastapi import HTTPException

        raise HTTPException(status_code=400, detail=str(exc)) from exc

    existing = db.scalar(
        select(EnvironmentVariable).where(
            EnvironmentVariable.project_id == project_id, EnvironmentVariable.key == clean_key
        )
    )
    if existing:
        from fastapi import HTTPException

        raise HTTPException(status_code=409, detail=f"{clean_key} is already defined for this project")

    var = EnvironmentVariable(
        project_id=project_id,
        key=clean_key,
        description=(description or "").strip() or None,
        required=required,
        is_secret=is_secret,
        created_by=created_by,
    )
    db.add(var)
    db.flush()

    if value is not None:
        try:
            secret_store.set_value(db, var.id, value)
        except secret_store.SecretStoreUnavailable:
            db.rollback()
            from fastapi import HTTPException

            raise HTTPException(
                status_code=503,
                detail="secret store unavailable: pgcrypto keyring missing — secret values cannot be stored",
            ) from None

    _event(
        db,
        project_id,
        EVENT_VARIABLE_DEFINED,
        {"key": clean_key, "required": required, "is_secret": is_secret,
         "created_by": str(created_by) if created_by else None},
    )
    db.commit()
    return variable_out(db, var)


def variable_out(db: Session, var: EnvironmentVariable) -> dict:
    return {
        "id": str(var.id),
        "project_id": str(var.project_id),
        "key": var.key,
        "description": var.description,
        "required": var.required,
        "is_secret": var.is_secret,
        "created_by": str(var.created_by) if var.created_by else None,
        "created_at": var.created_at.isoformat(),
        "updated_at": var.updated_at.isoformat(),
        "configured": has_value(db, var.id),
    }


def get_variable(db: Session, project_id: uuid.UUID, variable_id: uuid.UUID) -> EnvironmentVariable:
    var = db.scalar(
        select(EnvironmentVariable).where(
            EnvironmentVariable.id == variable_id, EnvironmentVariable.project_id == project_id
        )
    )
    if not var:
        from fastapi import HTTPException

        raise HTTPException(status_code=404, detail="environment variable not found")
    return var


def update_variable(
    db: Session,
    project: Project,
    var: EnvironmentVariable,
    requesting_user_id: uuid.UUID | None,
    description: str | None = None,
    required: bool | None = None,
    is_secret: bool | None = None,
    value: str | None = None,
    value_changed: bool = False,
) -> dict:
    """PATCH metadata and/or the value (value-only PATCH == rotation). Owner-gated
    once an owner exists. Value changes flow through secret_store only; the
    audit event records that it happened, never the value."""
    require_owner_if_set(project, requesting_user_id)

    changed: dict = {}
    if description is not None:
        var.description = description.strip() or None
        changed["description"] = True
    if required is not None:
        var.required = required
        changed["required"] = required
    if is_secret is not None:
        var.is_secret = is_secret
        changed["is_secret"] = is_secret

    had_value = has_value(db, var.id)
    if value_changed:
        try:
            secret_store.set_value(db, var.id, value or "")
        except secret_store.SecretStoreUnavailable:
            db.rollback()
            from fastapi import HTTPException

            raise HTTPException(
                status_code=503,
                detail="secret store unavailable: pgcrypto keyring missing — secret values cannot be stored",
            ) from None
        var.updated_at = datetime.now()
        _event(
            db,
            project.id,
            EVENT_SECRET_ROTATED if had_value else EVENT_VALUE_SET,
            {"key": var.key, "via": "patch"},
        )
    elif changed:
        var.updated_at = datetime.now()
        _event(db, project.id, "env_variable_updated", {"key": var.key, **changed})
    db.commit()
    return variable_out(db, var)


def remove_variable(
    db: Session,
    project: Project,
    var: EnvironmentVariable,
    requesting_user_id: uuid.UUID | None,
) -> dict:
    """DELETE metadata + ciphertext (CASCADE handles the grant rows; the
    ciphertext row is removed through the secret store before the ORM delete)."""
    require_owner_if_set(project, requesting_user_id)
    secret_store.clear_value(db, var.id)
    db.delete(var)
    _event(db, project.id, EVENT_VARIABLE_REMOVED, {"key": var.key})
    db.commit()
    return {"removed": True, "id": str(var.id), "key": var.key}


